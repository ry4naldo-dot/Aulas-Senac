    private void loadUserData() throws SQLException { 
        
        FoodDAO fodDao = new FoodDAO();
        List<Food> foods = fodDao.getFood();
        Object[][] data = new Object[foods.size()][6];
        
        //Preenchendo a tabela (colunas e linhas)
        for (int i = 0; i < foods.size(); i++) {
            
            data[i][0] = String.valueOf(foods.get(i).getId());
            data[i][1] = foods.get(i).getNomeF();
            data[i][2] = foods.get(i).getComida();
            data[i][3] = foods.get(i).getPeso();
            data[i][4] = foods.get(i).getDataFstring();
            data[i][5] = foods.get(i).getInfID();
            
        }
        
        Object[] nomeColuna = {"Id","Nome do Doador","Alimento","Peso","Data","CPF"};
        Tabela_Doacoes.setModel(new javax.swing.table.DefaultTableModel(data,nomeColuna));
        
    }

