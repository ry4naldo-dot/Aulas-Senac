    private void ButtonDoarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ButtonDoarActionPerformed
        // TODO add your handling code here:
        
        String addNomeF = NomeF.getText();
        String addItemF = ItemF.getText();
        double addQuantidadeF = Double.parseDouble(PesoF.getText().replace("", ""));
        String addDataVDF = DataFormattedTextField.getText();
        String addCPFF = cpfFFormattedTextField.getText();
        
        
        if(CaixadeVerificacao.isSelected()){
        
        if(addNomeF.isEmpty() || addItemF.isEmpty() || addQuantidadeF == 0 || addDataVDF.isEmpty() || addCPFF.isEmpty()){
            
            JOptionPane.showMessageDialog(this, "Por favor preencha todos os campos","ERRO",JOptionPane.ERROR_MESSAGE);
            
        }else{
            
            Food novoFood = new Food(0, addNomeF,addItemF,addQuantidadeF,addDataVDF,addCPFF);
            FoodDAO fodDao;
            
            try{
                
                fodDao = new FoodDAO();
                int res = fodDao.InserirFood(novoFood);
               
                if(res == 1){
                    
                   JOptionPane.showMessageDialog(this, "Doação criado com sucesso!","SUCESSO",JOptionPane.INFORMATION_MESSAGE);
                   this.clearForm();
                   loadUserData(); //Carregamento de dados do usuario
                   
                }else{
                    
                    JOptionPane.showMessageDialog(this, "Erro ocorrido ao inserir a doação","ERRO",JOptionPane.ERROR_MESSAGE);
                    
                }
                
            }catch(SQLException e){
                //System.out.println(e);
                //JOptionPane.showMessageDialog(this, "c" ,"c" ,JOptionPane.INFORMATION_MESSAGE);
                JOptionPane.showMessageDialog(this, "Erro ocorrido ao inserir a doação","ERRO",JOptionPane.ERROR_MESSAGE);
                
            }
            
        }
        
        //ListaDonations ld = new ListaDonations();
        //ld.setVisible(true);
        //dispose();
        }else{
            
            JOptionPane.showMessageDialog(this, "Você é um robô?","",JOptionPane.INFORMATION_MESSAGE);
            
        }
    }//GEN-LAST:event_ButtonDoarActionPerformed

    private void Tabela_DoacoesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_Tabela_DoacoesMouseClicked
        // TODO add your handling code here:
        
        int LinhaSelecionada = Tabela_Doacoes.getSelectedRow();
        
        if(LinhaSelecionada != -1){
            
            IdDoacaoSelecionado = Integer.parseInt(Tabela_Doacoes.getValueAt(LinhaSelecionada, 0).toString());
            NomeF.setText(Tabela_Doacoes.getValueAt(LinhaSelecionada, 1).toString());
            ItemF.setText(Tabela_Doacoes.getValueAt(LinhaSelecionada, 2).toString());
            PesoF.setText(Tabela_Doacoes.getValueAt(LinhaSelecionada, 3).toString());
            DataFormattedTextField.setText(Tabela_Doacoes.getValueAt(LinhaSelecionada, 4).toString());
            cpfFFormattedTextField.setText(Tabela_Doacoes.getValueAt(LinhaSelecionada, 5).toString());
            
        }
        
    }//GEN-LAST:event_Tabela_DoacoesMouseClicked

